function criarImagemFallback(materia, atividade) {
  const [corA, corB] = materia.cores;
  const titulo = escaparSvg(atividade.nome);
  const nomeMateria = escaparSvg(materia.nome);
  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 675">
      <defs>
        <linearGradient id="bg" x1="0%" y1="0%" x2="100%" y2="100%">
          <stop offset="0%" stop-color="${corA}" />
          <stop offset="100%" stop-color="${corB}" />
        </linearGradient>
      </defs>
      <rect width="1200" height="675" fill="url(#bg)" />
      <circle cx="980" cy="120" r="180" fill="rgba(255,255,255,0.12)" />
      <circle cx="180" cy="560" r="220" fill="rgba(255,255,255,0.08)" />
      <text x="70" y="120" fill="#ffffff" font-family="Arial, sans-serif" font-size="34" opacity="0.82">${nomeMateria}</text>
      <text x="70" y="260" fill="#ffffff" font-family="Arial, sans-serif" font-weight="700" font-size="58">${quebrarLinhasSvg(titulo, 32)}</text>
      <text x="70" y="610" fill="#ffffff" font-family="Arial, sans-serif" font-size="28" opacity="0.78">Preview protegido no link público</text>
    </svg>
  `;
  return `data:image/svg+xml;charset=UTF-8,${encodeURIComponent(svg)}`;
}

function quebrarLinhasSvg(texto, limite) {
  const palavras = texto.split(" ");
  const linhas = [];
  let atual = "";

  palavras.forEach((palavra) => {
    const teste = atual ? `${atual} ${palavra}` : palavra;
    if (teste.length > limite) {
      linhas.push(atual);
      atual = palavra;
      return;
    }
    atual = teste;
  });

  if (atual) {
    linhas.push(atual);
  }

  return linhas
    .map((linha, indice) => `<tspan x="70" dy="${indice === 0 ? 0 : 76}">${linha}</tspan>`)
    .join("");
}

function escaparSvg(texto) {
  return texto
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function criarCampo(titulo, conteudo) {
  const bloco = document.createElement("section");
  bloco.className = "atividade__campo";

  const heading = document.createElement("h2");
  heading.className = "atividade__titulo-campo";
  heading.textContent = titulo;
  bloco.appendChild(heading);

  if (Array.isArray(conteudo)) {
    const lista = document.createElement("ul");
    lista.className = "atividade__lista";
    conteudo.forEach((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      lista.appendChild(li);
    });
    bloco.appendChild(lista);
  } else {
    const texto = document.createElement("p");
    texto.className = "atividade__texto";
    texto.textContent = conteudo;
    bloco.appendChild(texto);
  }

  return bloco;
}

function obterLabelDoLink(link, index) {
  if (index === 0) {
    return "Acessar atividade";
  }

  if (link.label && !/\d/.test(link.label)) {
    return link.label;
  }

  return `Acessar atividade + ${numeroPorExtenso(index)}`;
}

function numeroPorExtenso(numero) {
  const numeros = [
    "zero",
    "um",
    "dois",
    "tres",
    "quatro",
    "cinco",
    "seis",
    "sete",
    "oito",
    "nove",
    "dez"
  ];

  return numeros[numero] || String(numero);
}

function criarBotoes(links) {
  const acoes = document.createElement("div");
  acoes.className = "atividade__acoes";

  links.forEach((link, index) => {
    const anchor = document.createElement("a");
    anchor.className = "btn link-atividade";
    anchor.href = link.url;
    anchor.target = "_blank";
    anchor.rel = "noopener noreferrer";
    anchor.textContent = obterLabelDoLink(link, index);
    acoes.appendChild(anchor);
  });

  return acoes;
}

function criarCard(materia, atividade) {
  const article = document.createElement("article");
  article.className = "conteudo";

  const boxImg = document.createElement("div");
  boxImg.className = "box_img";

  const img = document.createElement("img");
  img.className = "img_exemplo";
  img.src = atividade.imagem || criarImagemFallback(materia, atividade);
  img.alt = `Prévia da atividade ${atividade.nome}`;
  img.loading = "lazy";
  boxImg.appendChild(img);

  const descricao = document.createElement("div");
  descricao.className = "descricao";

  const titulo = document.createElement("h1");
  titulo.className = "Nome_Atividade";
  titulo.textContent = atividade.nome;
  descricao.appendChild(titulo);

  descricao.appendChild(criarCampo("Habilidades", atividade.habilidades));
  descricao.appendChild(criarCampo("Assunto", atividade.assunto));
  descricao.appendChild(criarCampo("Crítica pessoal", atividade.critica));
  descricao.appendChild(criarBotoes(atividade.links));

  article.append(boxImg, descricao);
  return article;
}

document.addEventListener("DOMContentLoaded", () => {
  const materiaKey = document.body.dataset.materia;
  const container = document.getElementById("lista-atividades");
  const materia = MATERIAS_PORTFOLIO[materiaKey];

  if (!container || !materia) {
    return;
  }

  materia.atividades.forEach((atividade) => {
    container.appendChild(criarCard(materia, atividade));
  });
});
