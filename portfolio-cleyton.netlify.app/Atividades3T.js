function criarPainelTerceiroTrimestre(chave, atividades) {
  const painel = criarElemento("section", "trimestre-painel");
  painel.id = `${chave}-trimestre-3`;
  painel.setAttribute("role", "tabpanel");
  painel.dataset.trimestre = "3";

  const intro = criarElemento("header", "trimestre-cabecalho");
  intro.appendChild(criarElemento("p", "trimestre-cabecalho__numero", "03"));
  const texto = criarElemento("div", "");
  texto.appendChild(criarElemento("h2", "trimestre-cabecalho__titulo", "3º Trimestre"));
  texto.appendChild(criarElemento("p", "trimestre-cabecalho__texto",
    `${atividades.length} ${atividades.length === 1 ? "atividade selecionada" : "atividades selecionadas"}. Orientações do Classroom podem exigir acesso à turma.`));
  intro.appendChild(texto);

  const lista = criarElemento("div", "trimestre-lista trimestre-lista--terceiro");
  atividades.forEach((atividade) => lista.appendChild(criarCardSegundoTrimestre(atividade, 3)));
  painel.append(intro, lista);
  return painel;
}
